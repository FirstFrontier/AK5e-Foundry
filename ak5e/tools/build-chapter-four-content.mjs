function referenceRecord(section, leadingRaw = "") {
  const rawSources = [leadingRaw, section.raw].map(raw => raw.trim()).filter(Boolean);
  const rawSource = rawSources.join("\n\n");
  return {
    id: `equipment-reference-${slugify(section.name)}`,
    kind: "reference",
    name: `Chapter 4: ${section.name}`,
    itemType: null,
    sourceHeading: section.name,
    content: toHtml(rawSource),
    rawSource,
    rawSources,
    tableData: null,
    systemData: {}
  };
}

function parseTableItems(text, heading, itemType) {
  const headingPattern = new RegExp(`^##### ${escapeRegExp(heading)}\\s*$`, "m");
  const headingMatch = headingPattern.exec(text);
  if (!headingMatch) throw new Error(`Missing Chapter 4 table: ${heading}`);
  const afterHeading = text.slice(headingMatch.index + headingMatch[0].length);
  const afterLines = afterHeading.split("\n");
  const tableStart = afterLines.findIndex(line => line.trim().startsWith("|"));
  const tableLines = [];
  for (let index = tableStart; index >= 0 && index < afterLines.length; index += 1) {
    if (!afterLines[index].trim().startsWith("|")) break;
    tableLines.push(afterLines[index]);
  }
  if (tableLines.length < 3) throw new Error(`Could not parse Chapter 4 table: ${heading}`);

  const headers = cells(tableLines[0]).map(cell => stripMarkup(cell).toLowerCase());
  let category = null;
  const records = [];
  for (const line of tableLines.slice(2)) {
    const values = cells(line);
    if (values.length <= 1) {
      category = stripMarkup(values[0] ?? "");
      continue;
    }
    const name = cleanName(values[0]);
    if (!name) continue;
    const row = Object.fromEntries(headers.map((header, index) => [header, stripMarkup(values[index] ?? "")]));
    const tableData = { category, ...row };
    records.push({
      id: `${itemType}-${slugify(name)}-${records.length}`,
      kind: itemType,
      name,
      itemType,
      sourceHeading: heading,
      content: tableItemHtml(name, heading, category, row),
      rawSource: line.trim(),
      tableData,
      systemData: physicalItemData(itemType, tableData)
    });
  }
  return records;
}

function featureRecord(kind, name, section) {
  return {
    id: `${kind}-${slugify(name)}-${section.index}`,
    kind,
    name,
    itemType: "feat",
    sourceHeading: section.name,
    content: toHtml(section.raw),
    rawSource: section.raw.trim(),
    tableData: null,
    systemData: {}
  };
}

function physicalItemData(itemType, row) {
  const weight = numberFrom(row.weight);
  const common = { quantity: 1, ...(weight === null ? {} : { weight: { value: weight, units: "lb" } }) };
  if (itemType === "weapon") {
    const damage = row.damage?.match(/(\d+)d(\d+)(?:\s*([+-]\s*\d+))?\s+(.+)/i);
    const range = row.properties?.match(/(?:Range|Thrown)\s*\((\d+)(?:\s*\/\s*(\d+))?\)/i);
    const properties = [];
    for (const [pattern, key] of [[/Two-Handed/i, "two"], [/Light/i, "lgt"], [/Loading/i, "lod"], [/Firearm/i, "fir"], [/Reach/i, "rch"], [/Thrown/i, "thr"], [/Finesse/i, "fin"], [/Versatile/i, "ver"]]) {
      if (pattern.test(row.properties ?? "")) properties.push(key);
    }
    return {
      ...common,
      type: { value: /ranged/i.test(row.category ?? "") ? "simpleR" : "simpleM", baseItem: "" },
      properties,
      ...(damage ? {
        damage: {
          base: {
            number: Number(damage[1]), denomination: Number(damage[2]), bonus: damage[3]?.replace(/\s/g, "") ?? "",
            types: [slugify(damage[4])], custom: { enabled: false, formula: "" }
          }
        }
      } : {}),
      ...(range ? { range: { value: Number(range[1]), long: range[2] ? Number(range[2]) : null, reach: null, units: "ft" } } : {})
    };
  }
  if (itemType === "equipment") {
    const armourClass = numberFrom(row["armour class"]);
    const category = String(row.category ?? "").toLowerCase();
    const type = category.includes("shield") ? "shield"
      : category.includes("light") ? "light"
      : category.includes("medium") ? "medium"
        : category.includes("heavy") ? "heavy" : "";
    const dex = /max\s*2/i.test(row["armour class"] ?? "") ? 2
      : /dexterity|dex\s+modifier/i.test(row["armour class"] ?? "") ? null : 0;
    return {
      ...common,
      ...(armourClass === null ? {} : { armor: { value: armourClass, dex } }),
      ...(type ? { type: { value: type, baseItem: "" } } : {})
    };
  }
  return common;
}

function numberFrom(value) {
  const match = String(value ?? "").match(/-?\d+(?:\.\d+)?/);
  return match ? Number(match[0]) : null;
}

function cells(line) {
  const values = line.trim().replace(/^\|/, "").replace(/\|$/, "").split("|");
  return values.map(value => value.trim());
}

function cleanName(value) {
  return stripMarkup(value)
    .replace(/^\*[^*]+\*$/g, "")
    .replace(/^\s*[•-]\s*/, "")
    .trim();
}

function stripMarkup(value) {
  return value
    .replace(/&emsp;/g, "")
    .replace(/<[^>]+>/g, "")
    .replace(/\*+/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

function tableItemHtml(name, heading, category, row) {
  const details = Object.entries(row)
    .filter(([header]) => header !== "name")
    .map(([header, value]) => `<dt>${escapeHtml(titleCase(header))}</dt><dd>${escapeHtml(value)}</dd>`)
    .join("");
  const categoryLine = category ? `<p><strong>Category:</strong> ${escapeHtml(category)}</p>` : "";
  return `<h3>${escapeHtml(name)}</h3><p><strong>Source table:</strong> ${escapeHtml(heading)}</p>${categoryLine}<dl>${details}</dl>`;
}

function titleCase(value) {
  return value.replace(/\b\w/g, character => character.toUpperCase());
}

function splitSections(text, level) {
  const marker = "#".repeat(level);
  const headings = [...text.matchAll(new RegExp(`^${marker} (.+)$`, "gm"))];
  return headings.map((heading, index) => {
    const contentStart = heading.index;
    const nextSameLevel = headings[index + 1]?.index ?? text.length;
    const nextHigher = new RegExp(`^#{1,${level - 1}} `, "gm");
    nextHigher.lastIndex = contentStart + 1;
    const nextHigherIndex = nextHigher.exec(text)?.index ?? text.length;
    return {
      index: contentStart,
      name: heading[1].trim(),
      raw: text.slice(contentStart, Math.min(nextSameLevel, nextHigherIndex)).trim()
    };
  });
}

function slugify(value) {
  return value.toLowerCase()
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function toHtml(raw) {
  return sourceToHtml(raw);
}

function escapeHtml(value) {
  return String(value).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

function assertUnique(values, label) {
  const seen = new Set();
  const duplicate = values.find(value => seen.has(value) || !seen.add(value));
  if (duplicate) throw new Error(`Duplicate ${label}: ${duplicate}`);
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}
