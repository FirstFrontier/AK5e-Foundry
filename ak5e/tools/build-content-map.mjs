function targetFor(chapter, entry) {
  if (chapter === 1) return { pack: "ak5e.rules", documentType: "JournalEntry" };
  if (chapter === 2) {
    if (entry.kind === "reference") return { pack: "ak5e.rules", documentType: "JournalEntry" };
    if (entry.kind === "origin-summon") return { pack: "ak5e.creatures", documentType: "Actor (npc)" };
    return { pack: "ak5e.origins", documentType: `Item (${entry.itemType})` };
  }
  if (chapter === 3) {
    if (entry.kind === "reference") return { pack: "ak5e.rules", documentType: "JournalEntry" };
    if (entry.kind === "class-summon") return { pack: "ak5e.creatures", documentType: "Actor (npc)" };
    return { pack: "ak5e.classes", documentType: `Item (${entry.itemType})` };
  }
  if (chapter === 4) return entry.kind === "reference"
    ? { pack: "ak5e.rules", documentType: "JournalEntry" }
    : { pack: "ak5e.equipment", documentType: `Item (${entry.itemType})` };
  if (chapter === 5) return entry.kind === "reference"
    ? { pack: "ak5e.rules", documentType: "JournalEntry" }
    : { pack: "ak5e.arts", documentType: `Item (${entry.itemType})` };
  if (chapter === 6) return entry.kind === "reference"
    ? { pack: "ak5e.rules", documentType: "JournalEntry" }
    : { pack: "ak5e.creatures", documentType: "Actor (npc)" };
  throw new Error(`Unknown chapter ${chapter}.`);
}

function extractTables(source) {
  const lines = source.replace(/\r\n/g, "\n").split("\n");
  const headingStack = [];
  const tables = [];
  let headingCount = 0;

  for (let index = 0; index < lines.length; index += 1) {
    const heading = lines[index].match(/^(#{1,6})\s+(.+)$/);
    if (heading) {
      const level = heading[1].length;
      headingStack.length = level - 1;
      headingStack[level - 1] = heading[2].trim();
      headingCount += 1;
    }
    if (!/^\|/.test(lines[index])) continue;
    const start = index;
    while (index + 1 < lines.length && /^\|/.test(lines[index + 1])) index += 1;
    if (index - start < 1) continue;
    tables.push({
      line: start + 1,
      headingPath: headingStack.filter(Boolean).join(" › "),
      header: lines[start].replace(/^\||\|$/g, "").trim().replace(/\s*\|\s*/g, " / ")
    });
  }
  return { headingCount, tables };
}

function rollTableFor(sourceFile, table) {
  if (sourceFile === "03_chapter_3_character_classes.txt" && /Double-Blind Trial/.test(table.headingPath)) return "Double-Blind Trial";
  if (sourceFile === "03_chapter_3_character_classes.txt" && /Machine Personality/.test(table.headingPath)) return "Machine Personality";
  if (sourceFile === "03_chapter_3_character_classes.txt" && /Tip of the Spear/.test(table.headingPath)) return "Tip of the Spear";
  if (sourceFile === "06_chapter_6_dwellers_of_terra.txt" && /Hole in the World/.test(table.headingPath)) return "Hole in the World";
  return null;
}

function describePack(pack) {
  return {
    "ak5e.arts": "Arts and Arts Pool Items",
    "ak5e.classes": "Classes, Branches, and Features",
    "ak5e.creatures": "Creatures and source-defined summons",
    "ak5e.equipment": "Equipment, properties, and rules Items",
    "ak5e.origins": "Origins, features, nationalities, and backgrounds",
    "ak5e.rules": "Chapter and supporting reference journals"
  }[pack] ?? "";
}

function escapeCell(value) {
  return String(value ?? "")
    .replaceAll("\\", "\\\\")
    .replaceAll("|", "\\|")
    .replaceAll("\n", "<br>")
    .replaceAll("`", "'");
}
