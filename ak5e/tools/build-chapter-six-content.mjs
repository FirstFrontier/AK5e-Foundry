import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { sourceToHtml } from "./source-html.mjs";
import { extractMonsterBlocks as extractStatblocks, parseMonsterStatblock } from "./monster-statblock.mjs";

const sourceUrl = new URL("../../AK5e_1.3.1_Foundry_Source/06_chapter_6_dwellers_of_terra.txt", import.meta.url);
const outputUrl = new URL("../scripts/chapter-six-content.mjs", import.meta.url);
const source = (await readFile(sourceUrl, "utf8")).replace(/\r\n/g, "\n");

const monsterBlocks = extractStatblocks(source);
if (!monsterBlocks.length) throw new Error("No Chapter 6 monster stat blocks found.");

const creatures = [];
for (const block of monsterBlocks) {
  const name = block.raw.match(/^##\s+(.+)$/m)?.[1]?.trim();
  if (!name) {
    const previous = creatures.at(-1);
    if (!previous) throw new Error("Found a statblock continuation without a preceding creature.");
    previous.rawSources ??= [previous.rawSource];
    previous.rawSources.push(block.raw.trim());
    previous.rawSource = `${previous.rawSource}\n\n${block.raw.trim()}`;
    previous.content = toHtml(previous.rawSource);
    previous.features = parseNpcFeatures(previous.rawSource);
    previous.continuationCount += 1;
    continue;
  }
  creatures.push(creatureRecord(name, block));
}

const firstStatBlock = monsterBlocks[0].index;
const characterSheetIndex = source.indexOf("## Character Sheet\n");
if (characterSheetIndex < 0) throw new Error("Missing Chapter 6 Character Sheet appendix marker.");
const supportingNotes = source
  .slice(firstStatBlock, characterSheetIndex)
  .replace(/^\{\{monster[^\n]*\n[\s\S]*?^}}\s*$/gm, "")
  .trim();
const supportingNoteFragments = source.slice(firstStatBlock, characterSheetIndex)
  .split(/^\{\{monster[^\n]*\n[\s\S]*?^}}\s*$/gm).map(fragment => fragment.trim()).filter(Boolean);

const records = [
  referenceRecord("GM Guidance", source.slice(0, firstStatBlock)),
  { ...referenceRecord("Statblock Supporting Notes", supportingNotes), rawSources: supportingNoteFragments },
  ...creatures
];

assertUnique(records.map(record => record.id), "record IDs");
if (creatures.length !== 145) throw new Error(`Expected 145 Chapter 6 creatures after continuations, found ${creatures.length}.`);
if (creatures.some(creature => creature.abilityScores.some(score => score === null))) {
  throw new Error("At least one Chapter 6 creature has an unparsed ability score.");
}
const incompleteArmour = creatures.filter(creature => creature.armorClass.value === null);
if (incompleteArmour.length) {
  throw new Error(`Unparsed armour class: ${incompleteArmour.map(creature => creature.name).join(", ")}`);
}
const sourceDefinedHitPoints = creatures.filter(creature => creature.hitPoints.maximum === null);
if (sourceDefinedHitPoints.length !== 1 || sourceDefinedHitPoints[0].name !== "Pathshaper Fractal") {
  throw new Error(`Unexpected non-numeric hit points: ${sourceDefinedHitPoints.map(creature => creature.name).join(", ")}`);
}

const output = [
  "/** This file is generated by tools/build-chapter-six-content.mjs. Do not edit by hand. */",
  `export const CHAPTER_SIX_CREATURES = ${JSON.stringify(records, null, 2)};`,
  ""
].join("\n");
await writeFile(outputUrl, output);

const counts = records.reduce((all, record) => {
  (all[record.kind] ??= []).push(record);
  return all;
}, {});
console.log(`Read ${fileURLToPath(sourceUrl)} and wrote ${records.length} records to ${fileURLToPath(outputUrl)}.`);
console.log(Object.entries(counts).map(([kind, entries]) => `${kind}: ${entries.length}`).join(", "));

function extractMonsterBlocks(text) {
  return [...text.matchAll(/^\{\{monster[^\n]*\n([\s\S]*?)^}}\s*$/gm)].map(match => ({
    index: match.index,
    raw: match[1].trim()
  }));
}

function creatureRecord(name, block) {
  const context = headingContext(source, block.index);
  const statblock = parseMonsterStatblock(block.raw);
  return {
    id: `creature-${slugify(name)}-${block.index}`,
    kind: "creature",
    name,
    sourceHeading: name,
    faction: context.faction,
    category: context.category ?? statblock.category,
    statblock,
    abilityScores: statblock.abilityScores,
    armorClass: statblock.armorClass,
    hitPoints: statblock.hitPoints,
    movement: statblock.movement,
    features: parseNpcFeatures(block.raw),
    continuationCount: 0,
    content: toHtml(block.raw),
    rawSource: block.raw
  };
}

function referenceRecord(name, raw) {
  return {
    id: `creature-reference-${slugify(name)}`,
    kind: "reference",
    name: `Chapter 6: ${name}`,
    sourceHeading: name,
    faction: null,
    category: null,
    statblock: null,
    abilityScores: null,
    armorClass: null,
    hitPoints: null,
    movement: null,
    features: null,
    continuationCount: 0,
    content: toHtml(raw),
    rawSource: raw.trim()
  };
}

function headingContext(text, index) {
  const preceding = text.slice(0, index);
  const factionHeading = [...preceding.matchAll(/^###\s+(.+)$/gm)]
    .filter(match => !/^(actions?|bonus actions?\.?|reactions?|legendary actions?|mythic actions?|lair actions?)$/i.test(match[1].trim()))
    .at(-1);
  const faction = factionHeading?.[1]?.trim() ?? "Uncategorized";
  const withinFaction = preceding.slice(factionHeading?.index ?? 0);
  const heading = [...withinFaction.matchAll(/^####\s+(.+)$/gm)].at(-1)?.[1]?.trim() ?? "";
  let category = /^(normal|elite|leader)s?$/i.test(heading)
    ? heading.replace(/s$/i, "").replace(/^./, character => character.toUpperCase())
    : null;
  if (!category && ["Sarkaz", "Seaborn", "Soldiers", "Ursus"].includes(faction)) category = "Normal";
  return { faction, category };
}

function parseNpcFeatures(raw) {
  const matches = [...raw.matchAll(/^\*\*\*(.+?)\*\*\*\s*(?:[.:]\s*)?(.*)$/gm)];
  return matches.map((match, index) => {
    const preceding = raw.slice(0, match.index);
    const section = [...preceding.matchAll(/^###\s+(.+)$/gm)].at(-1)?.[1]?.trim() ?? "Traits";
    const nextEntry = matches[index + 1]?.index ?? raw.length;
    const nextHeading = raw.slice(match.index + match[0].length, nextEntry).match(/^###\s+/m);
    const end = nextHeading ? match.index + match[0].length + nextHeading.index : nextEntry;
    const body = `${match[2]}${raw.slice(match.index + match[0].length, end)}`.trim().replace(/^:\s*$/gm, "");
    const name = match[1].trim().replace(/[.:]\s*$/, "").trim();
    return {
      name,
      section,
      content: toHtml(`##### ${name}\n${body}`),
      rawSource: body
    };
  });
}

function slugify(value) {
  return String(value).toLowerCase()
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function toHtml(raw) {
  return sourceToHtml(raw);
}

function assertUnique(values, label) {
  const seen = new Set();
  const duplicate = values.find(value => seen.has(value) || !seen.add(value));
  if (duplicate) throw new Error(`Duplicate ${label}: ${duplicate}`);
}
