import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { sourceToHtml } from "./source-html.mjs";
import { splitSourceSections } from "./source-sections.mjs";

const sourceUrl = new URL("../../AK5e_1.3.1_Foundry_Source/01_chapter_1_changing_the_game.txt", import.meta.url);
const outputUrl = new URL("../scripts/chapter-one-content.mjs", import.meta.url);
const source = (await readFile(sourceUrl, "utf8")).replace(/\r\n/g, "\n");
const sections = splitSourceSections(source, 3);
const byName = new Map(sections.map(section => [section.name, section]));

const required = [
  "Death Saving Throws",
  "No ASI Replacement Feats",
  "No Healing for Constructs",
  "No Multiclassing",
  "Physical/Arts Damage",
  "Skills and Proficiencies",
  "Spellcasting",
  "Spellcasting: Cantrips",
  "Damage Reduction (DR)",
  "Martial DC",
  "New Conditions",
  "Operator Skills",
  "Optional Rule: Alternate Classes",
  "Oripathy",
  "Rest Actions"
];
for (const name of required) {
  if (!byName.has(name)) throw new Error(`Missing Chapter 1 section: ${name}`);
}

const death = byName.get("Death Saving Throws");
const newMechanicsIndex = source.indexOf("## New Mechanics\n");
const damageReduction = byName.get("Damage Reduction (DR)");
if (newMechanicsIndex < 0) throw new Error("Missing Chapter 1 New Mechanics section.");

const records = [
  record("changed-mechanics", "Chapter 1: Changed Mechanics", [
    source.slice(0, death.index).trim(),
    ...[
      "No ASI Replacement Feats",
      "No Healing for Constructs",
      "No Multiclassing",
      "Physical/Arts Damage",
      "Skills and Proficiencies",
      "Spellcasting",
      "Spellcasting: Cantrips"
    ].map(name => byName.get(name).raw)
  ]),
  record("dying-and-mettle", "Chapter 1: Dying, Mettle, and Death's Door", [death.raw]),
  record("damage-reduction-and-martial-dc", "Chapter 1: Damage Reduction and Martial DC", [
    source.slice(newMechanicsIndex, damageReduction.index).trim(),
    damageReduction.raw,
    byName.get("Martial DC").raw
  ]),
  record("conditions", "Chapter 1: AK5e Conditions", [byName.get("New Conditions").raw]),
  record("operator-skills", "Chapter 1: Operator Skills", [byName.get("Operator Skills").raw]),
  record("alternate-classes", "Chapter 1: Optional Alternate Classes", [byName.get("Optional Rule: Alternate Classes").raw]),
  record("oripathy", "Chapter 1: Oripathy", [byName.get("Oripathy").raw]),
  record("rest-actions", "Chapter 1: Rest Actions", [byName.get("Rest Actions").raw])
];

const output = [
  "/** This file is generated by tools/build-chapter-one-content.mjs. Do not edit by hand. */",
  `export const CHAPTER_ONE_ENTRIES = ${JSON.stringify(records, null, 2)};`,
  ""
].join("\n");
await writeFile(outputUrl, output);
console.log(`Read ${fileURLToPath(sourceUrl)} and wrote ${records.length} records to ${fileURLToPath(outputUrl)}.`);

function record(slug, name, rawSources) {
  const retained = rawSources.map(raw => raw.trim()).filter(Boolean);
  return {
    slug,
    name,
    sourceHeading: retained.map(raw => raw.match(/^#{1,6}\s+(.+)$/m)?.[1]?.trim()).filter(Boolean).join("; "),
    content: retained.map(sourceToHtml).join("\n<hr>\n"),
    rawSource: retained.join("\n\n"),
    rawSources: retained
  };
}
