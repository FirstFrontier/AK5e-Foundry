import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { sourceToHtml } from "./source-html.mjs";

const sourceUrl = new URL("../../AK5e_1.3.1_Foundry_Source/05_chapter_5_arts.txt", import.meta.url);
const outputUrl = new URL("../scripts/chapter-five-content.mjs", import.meta.url);
const source = (await readFile(sourceUrl, "utf8")).replace(/\r\n/g, "\n");

const artsPointsIndex = source.indexOf("## Arts Points\n");
if (artsPointsIndex < 0) throw new Error("Missing Chapter 5 Arts Points section.");
const sections = splitSections(source, 2);
const byName = new Map(sections.map(section => [section.name, section]));
for (const name of ["Arts Points", "Standard Arts Pools", "Special Arts", "New Art Descriptions"]) {
  if (!byName.has(name)) throw new Error(`Missing Chapter 5 section: ${name}`);
}

const descriptions = splitSections(byName.get("New Art Descriptions").raw, 4);
const descriptionsStart = byName.get("New Art Descriptions").index;
const descriptionsIntro = source.slice(descriptionsStart, descriptionsStart + (descriptions[0]?.index ?? byName.get("New Art Descriptions").raw.length));
const records = [
  referenceRecord("Arts Overview", [source.slice(0, artsPointsIndex), descriptionsIntro]),
  ...["Arts Points", "Standard Arts Pools", "Special Arts"].map(name => referenceRecord(name, byName.get(name).raw))
];

const standardPools = splitSections(byName.get("Standard Arts Pools").raw, 4);
records.push(...standardPools.map(section => artPoolRecord("standard-art-pool", `Standard Arts Pool: ${section.name}`, section)));

const specialPools = splitSections(byName.get("Special Arts").raw, 4);
records.push(...specialPools.map(section => artPoolRecord("special-art-pool", `Special Arts Pool: ${section.name}`, section)));

records.push(...descriptions.map(spellRecord));

assertUnique(records.map(record => record.id), "record IDs");
const output = [
  "/** This file is generated by tools/build-chapter-five-content.mjs. Do not edit by hand. */",
  `export const CHAPTER_FIVE_ARTS = ${JSON.stringify(records, null, 2)};`,
  ""
].join("\n");
await writeFile(outputUrl, output);

const counts = records.reduce((all, record) => {
  (all[record.kind] ??= []).push(record);
  return all;
}, {});
console.log(`Read ${fileURLToPath(sourceUrl)} and wrote ${records.length} records to ${fileURLToPath(outputUrl)}.`);
console.log(Object.entries(counts).map(([kind, entries]) => `${kind}: ${entries.length}`).join(", "));

function referenceRecord(name, raw) {
  const rawSources = (Array.isArray(raw) ? raw : [raw]).map(value => value.trim()).filter(Boolean);
  const rawSource = rawSources.join("\n\n");
  return {
    id: `arts-reference-${slugify(name)}`,
    kind: "reference",
    name: `Chapter 5: ${name}`,
    itemType: null,
    sourceHeading: name,
    level: null,
    school: null,
    content: toHtml(rawSource),
    rawSource,
    rawSources
  };
}

function artPoolRecord(kind, name, section) {
  return {
    id: `${kind}-${slugify(section.name)}-${section.index}`,
    kind,
    name,
    itemType: "feat",
    sourceHeading: section.name,
    level: null,
    school: null,
    content: toHtml(section.raw),
    rawSource: section.raw.trim()
  };
}

function spellRecord(section) {
  const { level, school } = parseSpellMetadata(section.raw);
  const { sourceFields: castingMetadata, ...spellData } = parseSpellData(section.raw);
  return {
    id: `art-${slugify(section.name)}-${section.index}`,
    kind: "art",
    name: section.name,
    itemType: "spell",
    sourceHeading: section.name,
    level,
    school,
    spellData,
    castingMetadata,
    content: toHtml(section.raw),
    rawSource: section.raw.trim()
  };
}

function parseSpellMetadata(raw) {
  const line = raw.split("\n").find(entry => /^\*[^*]+\*$/.test(entry.trim()))?.trim();
  if (!line) return { level: null, school: null };
  const metadata = line.slice(1, -1).trim();
  const levelMatch = metadata.match(/^(\d+)(?:st|nd|rd|th)[-\s]Level\s+(.+)$/i);
  if (levelMatch) return { level: Number(levelMatch[1]), school: slugify(stripSchoolAnnotation(levelMatch[2])) };
  const cantripMatch = metadata.match(/^(.+)\s+Cantrip$/i);
  if (cantripMatch) return { level: 0, school: slugify(stripSchoolAnnotation(cantripMatch[1])) };
  return { level: null, school: slugify(stripSchoolAnnotation(metadata)) };
}

function stripSchoolAnnotation(value) {
  return value.replace(/\s*\([^)]*\)\s*$/, "").trim();
}

function parseSpellData(raw) {
  const casting = sourceField(raw, "Casting Time");
  const rangeText = sourceField(raw, "Range");
  const components = sourceField(raw, "Components");
  const durationText = sourceField(raw, "Duration");
  return {
    activation: parseActivation(casting),
    range: parseRange(rangeText),
    duration: parseDuration(durationText),
    properties: [
      /(?:^|,)\s*V(?:\s*,|$)/i.test(components) ? "vocal" : null,
      /(?:^|,)\s*S(?:\s*,|$)/i.test(components) ? "somatic" : null,
      /(?:^|,)\s*M(?:\s*\(|\s*,|$)/i.test(components) ? "material" : null,
      /concentration/i.test(durationText) ? "concentration" : null,
      /ritual/i.test(casting) ? "ritual" : null
    ].filter(Boolean),
    materials: { value: components.match(/M\s*\((.+)\)/i)?.[1] ?? "", consumed: false, cost: 0, supply: 0 },
    sourceFields: { casting, range: rangeText, components, duration: durationText }
  };
}

function sourceField(raw, label) {
  return raw.match(new RegExp(`^\\*\\*${label}:\\*\\*\\s*::?\\s*(.+)$`, "mi"))?.[1]?.trim() ?? "";
}

function parseActivation(value) {
  const normalized = value.toLowerCase();
  const type = normalized.startsWith("bonus action") ? "bonus"
    : normalized.startsWith("reaction") ? "reaction"
      : normalized.startsWith("action") ? "action"
        : normalized.includes("minute") ? "minute"
          : normalized.includes("hour") ? "hour"
            : "special";
  const cost = Number(normalized.match(/^(\d+)/)?.[1] ?? 1);
  return { type, value: cost, condition: value.includes(",") ? value.slice(value.indexOf(",") + 1).trim() : "" };
}

function parseRange(value) {
  if (/^touch$/i.test(value)) return { value: null, units: "touch", special: "" };
  if (/^self$/i.test(value)) return { value: null, units: "self", special: "" };
  const distance = value.match(/(\d+)\s*(feet|foot|ft|miles?|mi)/i);
  if (!distance) return { value: null, units: "spec", special: value };
  return { value: Number(distance[1]), units: /^m/i.test(distance[2]) ? "mi" : "ft", special: value };
}

function parseDuration(value) {
  if (/instant/i.test(value)) return { value: null, units: "inst", special: "" };
  const match = value.match(/(\d+)\s*(round|minute|hour|day)s?/i);
  if (!match) return { value: null, units: "spec", special: value };
  return { value: Number(match[1]), units: match[2].toLowerCase(), special: value };
}

function splitSections(text, level) {
  const marker = "#".repeat(level);
  const headings = [...text.matchAll(new RegExp(`^${marker} (.+)$`, "gm"))];
  return headings.map((heading, index) => {
    const contentStart = heading.index;
    const nextSameLevel = headings[index + 1]?.index ?? text.length;
    const nextHigher = new RegExp(`^#{1,${level - 1}} `, "gm");
    nextHigher.lastIndex = contentStart + 1;
    const nextHigherIndex = nextHigher.exec(text)?.index ?? text.length;
    return {
      index: contentStart,
      name: heading[1].trim(),
      raw: text.slice(contentStart, Math.min(nextSameLevel, nextHigherIndex)).trim()
    };
  });
}

function slugify(value) {
  return String(value).toLowerCase()
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function toHtml(raw) {
  return sourceToHtml(raw);
}

function assertUnique(values, label) {
  const seen = new Set();
  const duplicate = values.find(value => seen.has(value) || !seen.add(value));
  if (duplicate) throw new Error(`Duplicate ${label}: ${duplicate}`);
}
