import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { sourceToHtml } from "./source-html.mjs";
import { extractMonsterBlocks, parseMonsterStatblock, sizeKey } from "./monster-statblock.mjs";
import { splitSourceSections } from "./source-sections.mjs";

const sourceUrl = new URL("../../AK5e_1.3.1_Foundry_Source/02_chapter_2_character_origins.txt", import.meta.url);
const outputUrl = new URL("../scripts/chapter-two-content.mjs", import.meta.url);

const EXCLUDED_SECTIONS = new Set([
  "Parts of a Species",
  "Parts of a Nationality",
  "Parts of a Background"
]);

const SPECIES_VARIANT_PARENTS = new Map([
  ["Banshee", "Sarkaz"], ["Clanless", "Sarkaz"], ["Cyclopes", "Sarkaz"],
  ["Djall", "Sarkaz"], ["Gargoyle", "Sarkaz"], ["Nachzehrer", "Sarkaz"],
  ["Vampire", "Sarkaz"], ["Doomfire", "Draco"], ["Hearthfire", "Draco"],
  ["Hellfire", "Draco"]
]);

const source = (await readFile(sourceUrl, "utf8")).replace(/\r\n/g, "\n");
const speciesStart = source.indexOf("## Species\n");
const nationalityStart = source.indexOf("## Nationality\n");
const backgroundStart = source.indexOf("## Background\n");
if ([speciesStart, nationalityStart, backgroundStart].some(index => index < 0)) {
  throw new Error("Could not locate all Chapter 2 origin sections.");
}

const rareSpeciesStart = source.indexOf("## Rare Species\n", speciesStart);
if (rareSpeciesStart < 0 || rareSpeciesStart >= nationalityStart) throw new Error("Could not locate Chapter 2 Rare Species guidance.");

const ranges = [
  { kind: "species", start: speciesStart, end: nationalityStart },
  { kind: "nationality", start: nationalityStart, end: backgroundStart },
  { kind: "background", start: backgroundStart, end: source.length }
];

const records = ranges.flatMap(range => splitH3Sections(source.slice(range.start, range.end))
  .filter(section => !EXCLUDED_SECTIONS.has(section.name))
  .map(section => buildOriginRecord(range.kind, section)));

records.unshift(...ranges.map(range => buildGuidanceRecord(
  range.kind,
  source.slice(range.start, range.end),
  range.kind === "species" ? source.slice(0, speciesStart) : "",
  range.kind === "species" ? source.slice(rareSpeciesStart, firstH3Index(source, rareSpeciesStart, nationalityStart)) : ""
)));

for (const species of records.filter(record => record.kind === "species" && record.parent)) {
  const parent = records.find(record => record.kind === "species" && record.name === species.parent);
  if (!parent) throw new Error(`Missing parent species record for ${species.name}.`);
  species.systemData = structuredClone(parent.systemData);
  species.speciesSize = parent.speciesSize;
}

for (const species of records.filter(record => record.kind === "species")) {
  records.push(...extractSpeciesFeatures(species));
  records.push(...extractOriginSummons(species));
}

for (const nationality of records.filter(record => record.kind === "nationality")) {
  records.push(...extractUniqueBackgrounds(nationality));
}

const output = [
  "/** This file is generated by tools/build-chapter-two-content.mjs. Do not edit by hand. */",
  `export const CHAPTER_TWO_ORIGINS = ${JSON.stringify(records, null, 2)};`,
  ""
].join("\n");
assertUnique(records.map(record => record.id), "record IDs");
await writeFile(outputUrl, output);

const counts = records.reduce((grouped, record) => {
  (grouped[record.kind] ??= []).push(record);
  return grouped;
}, {});
console.log(`Read ${fileURLToPath(sourceUrl)} and wrote ${records.length} records to ${fileURLToPath(outputUrl)}.`);
console.log(Object.entries(counts).map(([kind, entries]) => `${kind}: ${entries.length}`).join(", "));

function splitH3Sections(text) {
  return splitSourceSections(text, 3);
}

function buildOriginRecord(kind, section) {
  const displayName = SPECIES_VARIANT_PARENTS.has(section.name)
    ? `${SPECIES_VARIANT_PARENTS.get(section.name)} — ${section.name}`
    : section.name;
  const nativeData = kind === "species" ? speciesNativeData(section.raw) : { systemData: {}, speciesSize: null };
  return {
    id: `${kind}-${slugify(displayName)}`,
    kind,
    name: displayName,
    sourceHeading: section.name,
    parent: SPECIES_VARIANT_PARENTS.get(section.name) ?? null,
    itemType: kind === "species" ? "race" : kind === "background" ? "background" : "feat",
    ...nativeData,
    content: toHtml(section.raw),
    rawSource: section.raw.trim()
  };
}

function buildGuidanceRecord(kind, rawRange, leadingRaw = "", additionalRaw = "") {
  const firstOrigin = splitH3Sections(rawRange).find(section => !EXCLUDED_SECTIONS.has(section.name));
  const rawSources = [leadingRaw, rawRange.slice(0, firstOrigin?.index ?? rawRange.length), additionalRaw]
    .map(raw => raw.trim())
    .filter(Boolean);
  const raw = rawSources.join("\n\n");
  const names = { species: "Species Guidance", nationality: "Nationality Guidance", background: "Background Guidance" };
  return {
    id: `${kind}-reference-guidance`,
    kind: "reference",
    name: `Chapter 2: ${names[kind]}`,
    sourceHeading: names[kind],
    parent: null,
    itemType: null,
    systemData: {},
    content: toHtml(raw),
    rawSource: raw,
    rawSources
  };
}

function firstH3Index(text, start, end) {
  const match = /^###\s+/gm;
  match.lastIndex = start;
  const found = match.exec(text);
  return found && found.index < end ? found.index : end;
}

function extractSpeciesFeatures(species) {
  return splitH5Sections(species.rawSource).map(section => ({
    id: `species-feature-${slugify(`${species.name}-${section.name}`)}`,
    kind: "species-feature",
    name: `${species.name}: ${section.name}`,
    sourceHeading: section.name,
    parent: species.name,
    itemType: "feat",
    systemData: {},
    content: toHtml(section.raw),
    rawSource: section.raw.trim()
  }));
}

function extractOriginSummons(species) {
  return extractMonsterBlocks(species.rawSource).map(block => {
    const name = block.raw.match(/^##\s+(.+)$/m)?.[1]?.trim();
    if (!name) throw new Error(`A summon statblock under ${species.name} has no name.`);
    return {
      id: `origin-summon-${slugify(`${species.name}-${name}`)}`,
      kind: "origin-summon",
      name,
      sourceHeading: name,
      parent: species.name,
      itemType: null,
      systemData: {},
      statblock: parseMonsterStatblock(block.raw),
      content: toHtml(block.raw),
      rawSource: block.raw
    };
  });
}

function extractUniqueBackgrounds(nationality) {
  return splitH5Sections(nationality.rawSource)
    .filter(section => /^Unique Background/.test(section.name))
    .map(section => {
      const match = section.name.match(/^Unique Background \((.+?)\):?$/);
      const name = match?.[1] ?? section.name.replace(/^Unique Background:?\s*/, "");
      return {
        id: `background-${slugify(name)}`,
        kind: "background",
        name,
        sourceHeading: section.name,
        parent: nationality.name,
        itemType: "background",
        systemData: {},
        content: toHtml(section.raw),
        rawSource: section.raw.trim()
      };
    });
}

function splitH5Sections(text) {
  return splitSourceSections(text, 5).filter(section => section.raw.length > 0);
}

function speciesNativeData(raw) {
  const creatureType = raw.match(/^\*\*\*Creature Type:\*\*\*\s*(.+)$/mi)?.[1]?.trim() ?? "";
  const typeMatch = creatureType.match(/\b(Celestial|Fiend|Humanoid)\b(?:\s*\(([^)]+)\))?/i);
  const sizeText = raw.match(/^\*\*\*Size:\*\*\*\s*(.+)$/mi)?.[1]?.trim() ?? "";
  const size = sizeText.match(/\b(?:your|their) size is (Tiny|Small|Medium|Large|Huge|Gargantuan)\b/i)?.[1]
    ?? sizeText.match(/\bsize category is (Tiny|Small|Medium|Large|Huge|Gargantuan)\b/i)?.[1];
  const speedText = raw.match(/^\*\*\*Speed:\*\*\*\s*(.+)$/mi)?.[1]?.trim() ?? "";
  const movement = { walk: 0, burrow: 0, climb: 0, fly: 0, swim: 0, hover: false, units: "ft", special: "" };
  for (const match of speedText.matchAll(/(?:(Walking|Burrowing|Climbing|Flying|Swimming)\s+Speed(?:\s+is|\s+of)?|base\s+Walking\s+Speed\s+is)\s*(\d+)\s*feet/gi)) {
    const mode = (match[1] ?? "walking").toLowerCase();
    const key = { walking: "walk", burrowing: "burrow", climbing: "climb", flying: "fly", swimming: "swim" }[mode];
    movement[key] = Number(match[2]);
  }
  if (/Climbing Speed (?:that is )?equal to your Walking Speed/i.test(speedText)) movement.climb = movement.walk;
  if (/Swimming Speed (?:that is )?equal to twice your Walking Speed/i.test(speedText)) movement.swim = movement.walk * 2;
  else if (/Swimming Speed (?:that is )?equal to your Walking Speed/i.test(speedText)) movement.swim = movement.walk;
  const senses = {};
  for (const line of raw.split("\n")) {
    const direct = line.match(/^(?:\*\*[^*]+\.\*\*\s*)?You have (\d+) feet of (Darkvision|Tremorsense|Blindsight|Truesight)\b/i);
    const gained = line.match(/^The specially adapted eyes[^\n]*?You gain (\d+) feet of (Darkvision)\b/i);
    const match = direct ?? gained;
    if (match) senses[match[2].toLowerCase()] = Number(match[1]);
  }
  return {
    speciesSize: size ? sizeKey(size) : "med",
    systemData: {
      type: typeMatch
        ? { value: typeMatch[1].toLowerCase(), custom: "", subtype: typeMatch[2] ?? "" }
        : { value: "custom", custom: creatureType, subtype: "" },
      movement,
      senses: { ranges: senses, units: "ft", special: "" }
    }
  };
}

function slugify(value) {
  return value.toLowerCase()
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function assertUnique(values, label) {
  const seen = new Set();
  const duplicate = values.find(value => seen.has(value) || !seen.add(value));
  if (duplicate) throw new Error(`Duplicate ${label} generated: ${duplicate}`);
}

function toHtml(raw) {
  return sourceToHtml(raw);
}
